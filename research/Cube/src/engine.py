"""Python access to the local compiled permutation evaluator."""
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


class Engine:
    def __init__(self):
        self.p = subprocess.Popen([str(ROOT / "bin/cube_engine")],
                                  stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                                  text=True, bufsize=1)

    def request(self, text, lines=1):
        self.p.stdin.write(text + "\n")
        self.p.stdin.flush()
        results = []
        for _ in range(lines):
            line = self.p.stdout.readline()
            if not line:
                raise RuntimeError("cube_engine stopped")
            results.append([int(x, 16) for x in line.split()])
        return results

    def permute(self, name, rounds, s):
        return self.request(f"p {name} {rounds} " + " ".join(f"{x:x}" for x in s))[0]

    def cube(self, name, rounds, iv, key, positions, base=(0,0), table=None):
        mode = "t" if table else "c"
        command = f"{mode} {name} {rounds} "
        command += " ".join(f"{x:x}" for x in (iv, *key, *base))
        command += f" {len(positions)} " + " ".join(map(str, positions))
        if table:
            command += f" {table[0]} {table[1]}"
        out = self.request(command, table[1]+1 if table else 1)
        return out if table else out[0]

    def linear_cube(self, name, rounds, iv, key, basis, base=(0,0)):
        """Sum over an affine nonce subspace generated by 128-bit basis vectors.

        Each basis element is a pair ``(low_word, high_word)``. The protocol
        enumerates the subspace in Gray-code order, so every query is reached
        by toggling one generator and all 2**len(basis) points are covered.
        """
        command = f"l {name} {rounds} "
        command += " ".join(f"{x:x}" for x in (iv, *key, *base))
        command += f" {len(basis)}"
        for lo, hi in basis:
            command += f" {lo:x} {hi:x}"
        return self.request(command)[0]

    def linear_cube_window(self, name, start, rounds, iv, key, basis,
                           base=(0, 0)):
        """Sum over an affine nonce subspace through a contiguous round window."""
        command = f"q {name} {rounds} {start} "
        command += " ".join(f"{x:x}" for x in (iv, *key, *base))
        command += f" {len(basis)}"
        for lo, hi in basis:
            command += f" {lo:x} {hi:x}"
        return self.request(command)[0]

    def close(self):
        self.p.stdin.close()
        self.p.wait()
        if self.p.returncode:
            raise RuntimeError(self.p.returncode)
